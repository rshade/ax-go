package main

import (
	"bytes"
	"context"
	"os"
	"testing"

	"github.com/rshade/ax-go"
)

func TestLLMsTxt(t *testing.T) {
	root, _ := newRootCommand(nil, "v9.9.9-golden", func() (string, error) {
		return "00000000-0000-7000-8000-000000000001", nil
	})
	if err := declareAgentContext(root); err != nil {
		t.Fatalf("declareAgentContext: %v", err)
	}
	if err := declareCommandSemantics(root); err != nil {
		t.Fatalf("declareCommandSemantics: %v", err)
	}
	// ax.Execute installs these persistent flags before the command runs.
	// GenerateLLMsTxt reflects the tree it is given, so the published document
	// adds the same flags first. The usage text matches prepareCommand.
	root.PersistentFlags().String("format", "", "output format: json or human")
	root.PersistentFlags().Bool("dry-run", false, "emit the envelope without side effects")
	root.PersistentFlags().Bool("yes", false, "confirm a confirmation-gated operation")
	root.PersistentFlags().Bool("strict", false, "escalate warnings to a validation error")
	root.PersistentFlags().String("idempotency-key", "", "opaque key used to prevent duplicate-create retries")

	var got bytes.Buffer
	err := ax.GenerateLLMsTxt(context.Background(), &got, root,
		ax.WithPreambleFile("llms.preamble.md"),
		ax.WithLinks([]ax.LinkSection{{
			Heading: "Docs",
			Links: []ax.Link{{
				Title: "ax-go",
				URL:   "https://github.com/rshade/ax-go",
				Notes: "library that generated this file",
			}},
		}}),
	)
	if err != nil {
		t.Fatalf("GenerateLLMsTxt: %v", err)
	}

	if *updateGolden {
		if err := os.WriteFile("llms.txt", got.Bytes(), 0o644); err != nil {
			t.Fatalf("update llms.txt: %v", err)
		}
	} else {
		want, err := os.ReadFile("llms.txt")
		if err != nil {
			t.Fatalf("read llms.txt: %v (run `go test ./examples/integration -run TestLLMsTxt -update`)", err)
		}
		if !bytes.Equal(got.Bytes(), want) {
			t.Fatalf("llms.txt drifted (%d generated bytes, %d committed bytes)", got.Len(), len(want))
		}
	}
	for _, name := range []string{"--dry-run", "--format", "--yes", "--strict", "--idempotency-key"} {
		if !bytes.Contains(got.Bytes(), []byte(name)) {
			t.Errorf("document missing %s", name)
		}
	}
}
